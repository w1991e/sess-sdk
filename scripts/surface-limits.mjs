// Sess's Surface text limits, derived from the reviewed contract snapshot (contract/openapi.json,
// the Sess runtime's SURFACE_TEXT_LIMITS rendered into the OpenAPI document). The
// runtime writes each limit once; this repository reads it only from the snapshot: the generated
// modules below (npm run generate) and the mention check (scripts/check-limits.mjs).

/** Each Surface text by the start of its schema line (Sess `SURFACE_TEXT_DOCS`), in order. */
export const LINE_STARTS = Object.freeze([
  ['title', "The page's heading: a question or a task,"],
  ['description', 'Optional context under the title:'],
  ['heading', 'A section heading:'],
  ['text', 'A paragraph of plain text (never markup):'],
  ['recordLabel', 'Optional caption above the record:'],
  ['recordKey', "A row's name, shown verbatim:"],
  ['recordValue', "A row's value, shown verbatim:"],
  ['fieldLabel', 'What the field asks for:'],
  ['fieldDescription', 'Optional help, shown under its own field:'],
  ['optionLabel', 'The words shown for one choice:'],
  ['actionLabel', 'A button:'],
  ['itemsLabel', 'Optional caption of an items card:'],
  ['itemName', 'What one line is, shown verbatim;'],
  ['itemDetail', 'Optional second line under the name:'],
  ['totalLabel', "A totals line's label:"],
  ['quantityUnit', 'Optional unit shown after an editable quantity:'],
  ['ratingLabel', 'Optional words at one end of a rating,'],
]);

function* nodes(value) {
  if (Array.isArray(value)) for (const item of value) yield* nodes(item);
  else if (value !== null && typeof value === 'object') {
    yield value;
    for (const item of Object.values(value)) yield* nodes(item);
  }
}

/**
 * The limits from a contract document: each text's maxLength (every schema carrying its line must
 * agree, and its line must say "at most" that number), and the title's and the field label's good
 * lengths ("about N characters" in their lines).
 */
export function deriveLimits(doc) {
  const found = new Map();
  const guides = {};
  for (const node of nodes(doc)) {
    if (typeof node.description !== 'string' || typeof node.maxLength !== 'number') continue;
    const entry = LINE_STARTS.find(([, start]) => node.description.startsWith(start));
    if (!entry) continue;
    const [key] = entry;
    const said = /\bat most (\d+)/.exec(node.description);
    if (!said || Number(said[1]) !== node.maxLength)
      throw new Error(`contract: the ${key} line says "${said?.[0]}" but its maxLength is ${node.maxLength}`);
    const before = found.get(key);
    if (before !== undefined && before !== node.maxLength)
      throw new Error(`contract: ${key} has two limits, ${before} and ${node.maxLength}`);
    found.set(key, node.maxLength);
    const about = /\babout (\d+) characters/.exec(node.description);
    if (about && (key === 'title' || key === 'fieldLabel')) guides[key] = Number(about[1]);
  }
  const missing = LINE_STARTS.map(([key]) => key).filter((key) => !found.has(key));
  if (missing.length) throw new Error(`contract: no limit found for ${missing.join(', ')}`);
  if (guides.title === undefined || guides.fieldLabel === undefined)
    throw new Error('contract: the title or field label line names no good length');
  const limits = Object.fromEntries(LINE_STARTS.map(([key]) => [key, found.get(key)]));
  return { ...limits, titleGuide: guides.title, fieldLabelGuide: guides.fieldLabel };
}

/** The generated TypeScript module (formatted by the caller). */
export function limitsModule(limits) {
  const lines = Object.entries(limits).map(([key, value]) => `  ${key}: ${value},`);
  return [
    '// Generated by scripts/check-contract.mjs from contract/openapi.json (npm run generate); do not',
    "// edit. Sess writes each limit once (the runtime's SURFACE_TEXT_LIMITS); this is that snapshot.",
    '',
    '/**',
    " * Sess's limits for what a person reads, in Unicode code points, as the runtime checks them on",
    ' * create and publish; nothing is ever truncated. `titleGuide` and `fieldLabelGuide` are the good',
    ' * lengths of a title and a field label, not limits.',
    ' */',
    'export const SURFACE_TEXT_LIMITS = Object.freeze({',
    ...lines,
    '});',
    '',
  ].join('\n');
}

